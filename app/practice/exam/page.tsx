import { headers } from "next/headers";
import Link from "next/link";

export const metadata = { title: "考试模式" };

export default async function ExamStartPage() {
  const requestHeaders = await headers();
  const ownerId = requestHeaders.get("oai-authenticated-user-id") ?? "local-demo";

  const res = await fetch(`http://127.0.0.1:3051/api/papers`, {
    headers: { "oai-authenticated-user-id": ownerId },
    cache: "no-store",
  });
  let papers: Array<{ id: string; title: string; created_at: string }> = [];
  if (res.ok) {
    const data = await res.json();
    papers = (data.papers ?? []).filter((p: any) => p.settings_json?.autoGenerated);
  }

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <h1 className="text-xl font-bold">考试模式</h1>
        <p className="text-sm text-muted-foreground">设置考试时长，时间到自动交卷，答错自动记入错题本</p>
      </div>

      <div className="grid md:grid-cols-3 gap-4">
        {papers.length === 0 ? (
          <div className="col-span-3 px-4 py-8 text-center text-muted-foreground rounded-xl border bg-card">
            暂无可考试的试卷。请先在「组卷」页面生成试卷。
          </div>
        ) : (
          papers.map((paper) => (
            <ExamCard key={paper.id} paper={paper} />
          ))
        )}
      </div>
    </div>
  );
}

function ExamCard({ paper }: { paper: { id: string; title: string; created_at: string } }) {
  return (
    <Link
      href={`/practice/exam/${paper.id}/start`}
      className="rounded-xl border p-4 hover:border-primary/50 transition-colors"
    >
      <div className="text-sm font-medium">{paper.title}</div>
      <div className="text-xs text-muted-foreground mt-1">
        {new Date(paper.created_at).toLocaleDateString("zh-CN")}
      </div>
      <div className="mt-3 flex items-center gap-2 text-xs text-primary">
        <span>⏱</span> 设置时长并开始
      </div>
    </Link>
  );
}
