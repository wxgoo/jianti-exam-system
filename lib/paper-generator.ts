/**
 * 随机抽题组卷算法
 *
 * 借鉴 WTS wts_random_step、yf-exam generateByRepo、江苏小学生成器难度配比/A-B 卷。
 * 从已审核题库中按类型/难度/数量抽题，支持难度配比和基于 seed 的 A-B 卷。
 */

import { getSqlite } from "../db";
import { documentScopeSql, type EducationScope } from "./education-scope";
import { now } from "./server";
import type { QuestionType } from "./types";

export type Difficulty = "easy" | "medium" | "hard";

export type QuestionQuota = {
  type: QuestionType;
  count: number;
  score: number;
  difficultyRatio?: { easy: number; medium: number; hard: number }; // 百分比，总和 100
};

export type GeneratePaperInput = {
  title: string;
  subtitle?: string;
  quotas: QuestionQuota[]; // 每个板块的题型/数量/分值/难度配比
  seed?: string; // 用于 A-B 卷：相同 seed 生成相同题目顺序
  versionCode?: string; // "A" | "B" | ...
  settings?: Record<string, unknown>;
};

export type SelectedQuestion = {
  id: string;
  position: number;
  score: number;
  type: QuestionType;
  difficulty: Difficulty;
};

function deterministicHash(value: string): number {
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = ((hash << 5) - hash + value.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

function seededShuffle<T>(array: T[], seed: string): T[] {
  const result = [...array];
  let seedValue = deterministicHash(seed);
  for (let i = result.length - 1; i > 0; i -= 1) {
    seedValue = (seedValue * 1103515245 + 12345) | 0;
    const j = (seedValue >>> 0) % (i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/**
 * 按配比从已审核题库中选题。返回选中的题目列表（不含题干，仅 id/position/score/type/difficulty）。
 */
export function selectQuestionsByQuota(
  ownerId: string,
  scope: EducationScope,
  quotas: QuestionQuota[],
  seed?: string,
): SelectedQuestion[] {
  const sqlite = getSqlite();
  const filter = documentScopeSql(scope);

  const selected: SelectedQuestion[] = [];
  let position = 0;

  for (const quota of quotas) {
    const params: unknown[] = [ownerId, ...filter.params];

    let sql = `
      SELECT q.id, q.difficulty
      FROM questions q JOIN documents d ON d.id = q.document_id
      WHERE d.owner_id = ?${filter.sql} AND q.status = 'approved' AND q.type = ?
    `;
    params.push(quota.type);

    const candidates = sqlite.prepare(sql).all(...params) as Array<{
      id: string;
      difficulty: Difficulty;
    }>;

    if (!candidates.length) continue;

    let pool: string[];
    if (quota.difficultyRatio) {
      const { easy, medium, hard } = quota.difficultyRatio;
      const total = easy + medium + hard || 100;
      const easyCount = Math.floor((quota.count * easy) / total);
      const mediumCount = Math.floor((quota.count * medium) / total);
      const hardCount = quota.count - easyCount - mediumCount;

      const byDifficulty: Record<Difficulty, string[]> = { easy: [], medium: [], hard: [] };
      for (const c of candidates) byDifficulty[c.difficulty].push(c.id);

      const pick = (ids: string[], n: number) => {
        const shuffled = seed ? seededShuffle(ids, `${seed}-${quota.type}`) : ids;
        return shuffled.slice(0, Math.min(n, shuffled.length));
      };

      pool = [
        ...pick(byDifficulty.easy, easyCount),
        ...pick(byDifficulty.medium, mediumCount),
        ...pick(byDifficulty.hard, hardCount),
      ];
    } else {
      pool = seed ? seededShuffle(candidates.map((c) => c.id), `${seed}-${quota.type}`) : candidates.map((c) => c.id);
    }

    const take = pool.slice(0, quota.count);
    for (const id of take) {
      selected.push({ id, position: position + 1, score: quota.score, type: quota.type, difficulty: "medium" });
      position += 1;
    }
  }

  return selected;
}

/**
 * 生成试卷：选题 + 写入 papers/paper_items + 记录 paper_versions（A-B 卷）。
 * 返回 { paperId, questions: SelectedQuestion[] }。
 */
export function generatePaper(
  input: GeneratePaperInput,
  ownerId: string,
  scope: EducationScope,
) {
  const sqlite = getSqlite();
  const timestamp = now();
  const versionCode = input.versionCode ?? "A";
  const seed = input.seed ?? crypto.randomUUID();

  // 选题
  const selected = selectQuestionsByQuota(ownerId, scope, input.quotas, seed);

  if (!selected.length) {
    return { error: "未能按配比抽取到任何题目，请检查题库数量或难度设置" } as const;
  }

  const id = crypto.randomUUID();
  const versionId = crypto.randomUUID();

  sqlite.transaction(() => {
    sqlite.prepare(
      `INSERT INTO papers (id, owner_id, title, subtitle, settings_json, created_at, updated_at)
       VALUES (?, ?, ?, ?, ?, ?, ?)`,
    ).run(
      id,
      ownerId,
      input.title,
      input.subtitle ?? "",
      JSON.stringify({ ...input.settings, ...scope, autoGenerated: true, versionCode, seed }),
      timestamp,
      timestamp,
    );

    const insertItem = sqlite.prepare(
      "INSERT INTO paper_items (paper_id, question_id, position, score) VALUES (?, ?, ?, ?)",
    );
    for (const q of selected) {
      insertItem.run(id, q.id, q.position, q.score);
    }

    // 记录 A-B 卷版本
    const questionIdsJson = JSON.stringify(selected.map((q) => q.id));
    sqlite.prepare(
      `INSERT INTO paper_versions (id, paper_id, version_code, question_ids_json, seed, created_at)
       VALUES (?, ?, ?, ?, ?, ?)`,
    ).run(versionId, id, versionCode, questionIdsJson, seed, timestamp);
  }).immediate();

  return {
    paperId: id,
    questions: selected,
    versionCode,
    seed,
  } as const;
}

export { seededShuffle, deterministicHash };
